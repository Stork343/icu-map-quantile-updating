args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 5L) stop("Supply code directory, input model, nodes, parameter CSV and output model")
source(file.path(args[1], "fit_random_slope_lqmm.R"))
source(file.path(args[1], "export_random_slope_parameters.R"))
fit <- readRDS(args[2])
nodes <- as.integer(args[3])
if (!is.finite(nodes) || nodes <= attr(fit$QUAD, "k")) stop("Refinement requires a higher quadrature order")
validate_slope_fit(fit)
started <- proc.time()
fit <- refine_slope_fit(fit, nodes)
saveRDS(fit, args[5])
saveRDS(fit, paste0(args[5], ".stage_", nodes))
print(export_slope_parameters(fit, args[4]))
print(proc.time() - started)
